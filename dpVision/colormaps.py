def make_colormap(name='jet', n=256):
    """Zwraca tablicę (n, 3) float32 z kolorami colormapy.
    Dostępne: 'jet', 'rainbow', 'hot', 'cool', 'gray', 'terrain', 'skala'.
    Można też podać własną tablicę (n, 3) float.
    """
    if isinstance(name, np.ndarray):
        arr = np.asarray(name, dtype=np.float32)
        if arr.shape == (n, 3):
            return arr
        t_src = np.linspace(0.0, 1.0, arr.shape[0])
        t_dst = np.linspace(0.0, 1.0, n)
        return np.stack([
            np.interp(t_dst, t_src, arr[:, ch]).astype(np.float32)
            for ch in range(3)
        ], axis=1)

    data = COLORMAPS.get(name, COLORMAPS['jet'])
    if isinstance(data, np.ndarray):
        # pre-built dense palette (e.g. 'skala') – resample if n differs
        if len(data) == n:
            return data.astype(np.float32)
        t_src = np.linspace(0.0, 1.0, len(data))
        t_dst = np.linspace(0.0, 1.0, n)
        return np.stack([
            np.interp(t_dst, t_src, data[:, ch]).astype(np.float32)
            for ch in range(3)
        ], axis=1)

    stops = data
    keys = np.array([s[0] for s in stops], dtype=np.float32)
    colors = np.array([s[1] for s in stops], dtype=np.float32)
    t = np.linspace(0.0, 1.0, n, dtype=np.float32)
    return np.stack([
        np.interp(t, keys, colors[:, ch]).astype(np.float32)
        for ch in range(3)
    ], axis=1)
